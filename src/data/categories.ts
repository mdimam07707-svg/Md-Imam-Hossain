export function catLabel(name: string, lang: Language): string {
  if (lang === 'bn') return name;
  const m = CATX[name];
  return m ? m[LI[lang]] : name;
}

export function groupLabel(title: string, lang: Language): string {
  if (lang === 'bn') return title;
  const m = GTX[title];
  return m ? m[LI[lang]] : title;
}

export function findCategoryIcon(catName: string): string {
  for (const g of CATEGORY_GROUPS) {
    const found = g.items.find((i) => i.name === catName);
    if (found) return found.icon;
  }
  return 'dots';
}
