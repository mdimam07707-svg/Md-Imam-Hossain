export function tr(lang: Language, key: string): string {
  return (T[lang] && T[lang][key]) || T.bn[key] || key;
}

const BN_D = '০১২৩৪৫৬৭৮৯';
export function toBn(s: string | number): string {
  return String(s).replace(/[0-9]/g, (d) => BN_D[Number(d)]);
}

export function money(n: number, lang: Language): string {
  const val = Number(n) || 0;
  const s = val.toLocaleString('en-IN', { maximumFractionDigits: 2 });
  return '৳ ' + (lang === 'bn' ? toBn(s) : s);
}

export function fmtNum(n: number, lang: Language): string {
  const val = Math.round(Number(n) || 0);
  const s = val.toLocaleString('en-IN');
  return lang === 'bn' ? toBn(s) : s;
}

export function fmtDate(iso: string, lang: Language): string {
  if (!iso) return '';
  const d = new Date(iso + 'T00:00:00');
  const loc = { bn: 'bn-BD', en: 'en-GB', ar: 'ar-EG', zh: 'zh-CN' }[lang] || 'bn-BD';
  try {
    return d.toLocaleDateString(loc, { day: 'numeric', month: 'short', year: 'numeric' });
  } catch {
    return iso;
  }
}

export function typeLabel(ty: TxType, lang: Language): string {
  if (ty === 'income') return tr(lang, 'income');
  if (ty === 'expense') return tr(lang, 'expense');
  if (ty === 'debt') return tr(lang, 'debtT');
  return tr(lang, 'paonaT');
}
